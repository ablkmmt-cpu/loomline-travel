#!/usr/bin/env node

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CATALOG_FILE = join(ROOT, "data", "standard-routes.json");
const BROWSER_CATALOG_FILE = join(ROOT, "assets", "standard-routes-catalog.js");
const CITY_DATA_DIR = join(ROOT, "data", "cities");
const CHECK_ONLY = process.argv.includes("--check");

const catalog = JSON.parse(readFileSync(CATALOG_FILE, "utf8"));
if (!Array.isArray(catalog.routes) || !catalog.routes.length) {
  throw new Error("data/standard-routes.json must contain at least one route");
}

const requiredFields = [
  "id", "code", "cityCode", "citySlug", "cityName", "title", "days", "nights",
  "summary", "highlights", "interests", "image", "imageAlt", "priceReady"
];
const codes = new Set();
const ids = new Set();

catalog.routes.forEach((route, index) => {
  requiredFields.forEach((field) => {
    if (route[field] === undefined || route[field] === null || route[field] === "") {
      throw new Error(`routes.${index}.${field} is required`);
    }
  });
  if (!/^[A-Z]{2,3}-STD-\d{3}$/.test(route.code)) {
    throw new Error(`routes.${index}.code must follow CITY-STD-001 format`);
  }
  if (codes.has(route.code)) throw new Error(`duplicate route code: ${route.code}`);
  if (ids.has(route.id)) throw new Error(`duplicate route id: ${route.id}`);
  if (!Array.isArray(route.interests)) throw new Error(`routes.${index}.interests must be an array`);
  if (!Number.isInteger(route.days) || !Number.isInteger(route.nights)) {
    throw new Error(`routes.${index}.days and nights must be integers`);
  }
  if (route.priceReady && !Number.isFinite(route.priceCny)) {
    throw new Error(`routes.${index}.priceCny is required when priceReady is true`);
  }
  if (route.detailReady && !route.detailPath) {
    throw new Error(`routes.${index}.detailPath is required when detailReady is true`);
  }
  codes.add(route.code);
  ids.add(route.id);
});

console.log(`Validated ${catalog.routes.length} standard routes.`);
if (CHECK_ONLY) process.exit(0);

const browserCatalog = `/* Generated from data/standard-routes.json. Do not edit this file directly. */\nwindow.LOOMLINE_STANDARD_ROUTES = ${JSON.stringify(catalog.routes, null, 2)};\n`;
writeFileSync(BROWSER_CATALOG_FILE, browserCatalog, "utf8");
console.log("Generated assets/standard-routes-catalog.js");

const cityFiles = readdirSync(CITY_DATA_DIR).filter((file) => file.endsWith(".json"));
for (const file of cityFiles) {
  const city = JSON.parse(readFileSync(join(CITY_DATA_DIR, file), "utf8"));
  const result = spawnSync(
    process.execPath,
    [join(ROOT, "tools", "gen-city-pages.mjs"), "--city", city.slug, "--publish"],
    { cwd: ROOT, encoding: "utf8" },
  );
  if (result.status !== 0) {
    throw new Error(result.stderr || result.stdout || `failed to publish ${city.slug}`);
  }
  process.stdout.write(result.stdout);
}
